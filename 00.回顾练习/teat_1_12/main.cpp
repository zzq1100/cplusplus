#include<stdio.h>
int main()
{
	typedef struct student
	{
		int ID;
		char name[10];
		double sore;
	}stu;
	stu s1, s2;
	scanf("%d %s %lf", &s1.ID, s1.name, &s1.sore);
	scanf("%d %s %lf", &s2.ID, s2.name, &s2.sore);
	if (s1.sore > s2.sore)
		printf("%d %s %.1lf", s1.ID, s1.name, s1.sore);
	else
		printf("%d %s %.1lf", s2.ID, s2.name, s2.sore);


	return 0;
}

